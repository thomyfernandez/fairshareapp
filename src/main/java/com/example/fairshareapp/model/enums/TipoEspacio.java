package com.example.fairshareapp.model.enums;

/**
 * Enumeracion que define las diferentes tipologias de espacios compartidos en la aplicacion.
 */
public enum TipoEspacio {

    /**
     * Espacio compartido para viviendas, alquileres o gastos de convivencia en el hogar.
     */
    HOGAR,

    /**
     * Espacio temporal para viajes, vacaciones o escapadas conjuntas.
     */
    VIAJE,

    /**
     * Espacio para parejas que comparten finanzas o gastos comunes.
     */
    PAREJA,

    /**
     * Espacio destinado a proyectos colaborativos o ambitos laborales.
     */
    TRABAJO,

    /**
     * Espacio generico para otros fines compartidos.
     */
    OTRO
}
