package com.example.fairshareapp.model.enums;

/**
 * Enumeracion que define los roles posibles de un miembro dentro de un espacio compartido.
 */
public enum RolMiembro {

    /**
     * Miembro con permisos de administracion sobre el espacio (creador o promovido).
     */
    ADMIN,

    /**
     * Miembro con permisos estandar dentro del espacio.
     */
    MIEMBRO
}
